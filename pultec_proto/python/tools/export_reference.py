"""Writes cpp/reference/reference.txt: digital coefficients + tube samples
computed by the Python model, so the C++ core can be checked against it.
Run from repo root:  python python/tools/export_reference.py
"""
import os, sys
import numpy as np
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from pultec import Params, saturation as S
from pultec import analog

PRESETS = [
    Params(),
    Params(lf_freq=60, lf_boost=2.5, lf_cut=2.5),
    Params(lf_freq=20, lf_boost=10, lf_cut=10),
    Params(lf_freq=100, lf_boost=7, lf_cut=3),
    Params(hf_freq=16000, hf_boost=10, hf_bw=0),
    Params(hf_freq=3000, hf_boost=6, hf_bw=10),
    Params(hf_freq=8000, hf_boost=4, hf_bw=5, hf_cut_freq=5000, hf_cut=5),
    Params(hf_cut_freq=20000, hf_cut=10),
    Params(lf_freq=30, lf_boost=5, lf_cut=1, hf_freq=12000, hf_boost=8, hf_bw=3,
           hf_cut_freq=10000, hf_cut=2),
]
out = ["# generated by python/tools/export_reference.py -- do not edit",
       "# SECTIONS lf_freq lf_boost lf_cut hf_freq hf_boost hf_bw hf_cut_freq hf_cut fs nsec [b0 b1 b2 a1 a2]*"]
for fs in (96000, 192000):
    for p in PRESETS:
        sos = analog.digital_sos(analog.analog_sections(p), fs)
        vals = [p.lf_freq, p.lf_boost, p.lf_cut, p.hf_freq, p.hf_boost, p.hf_bw,
                p.hf_cut_freq, p.hf_cut, fs, len(sos)]
        s = " ".join(repr(float(v)) for v in vals[:-1]) + f" {len(sos)}"
        for r in sos:
            s += " " + " ".join(repr(float(v)) for v in (r[0], r[1], r[2], r[4], r[5]))
        out.append("SECTIONS " + s)
for k in (S.k_calibrated(), 0.1, 1.0):
    for x in (-0.9, -0.3, 0.0, 0.2, 0.7):
        out.append(f"TUBE {k!r} {x!r} {float(S.tube(np.array(x), k))!r}")
dest = os.path.join(os.path.dirname(__file__), "..", "..", "cpp", "reference", "reference.txt")
open(dest, "w").write("\n".join(out) + "\n")
print("wrote", os.path.normpath(dest), len(out), "lines; K_cal =", repr(S.k_calibrated()))
